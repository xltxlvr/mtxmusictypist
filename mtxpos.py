#!/usr/bin/env python3
"""
mtxpos.py - PDF 위의 마디 위치 기록(사이드카) 지원. GUI 비의존.

컴파일할 때 mtxpos.tex 를 `%% \\input mtxpos` 로 끼워 넣으면, MusiXTeX 가 마디선을
놓을 때마다(\\n@wbar) 현재 쪽/좌표를 <job>.mtxpos 에 한 줄씩 적는다.

    B,<barno>,<page>,<x_sp>,<y_sp>,<systemheight_pt>,<linpos_pt>

  * x,y   : \\pdflastxpos / \\pdflastypos (sp, 쪽 왼쪽 아래 기준)
  * 레코드는 '마디가 끝나는 마디선' 위치이다.  마지막 패스의 파일이 이긴다.
  * 이 값들은 아직 실제 MusiXTeX 로 검증하지 못했다.  개수가 pmx 마디 수와 다르면
    위치 기능을 끄고(소스<->마디 점프만 사용) 상태줄에 알린다.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Optional, Tuple

SP_PER_BP = 65536.0 * 72.27 / 72.0     # 1 bp = 65781.76 sp
PT_PER_BP = 72.27 / 72.0

MTXPOS_TEX = r"""% mtxpos.tex -- generated by mtxMusicTypist; records bar-line positions.
\catcode`\@=11
\ifx\n@wbar\undefined
  \message{mtxpos: musixtex is not loaded yet, hook disabled}%
  \expandafter\endinput
\fi
\ifx\mtx@posloaded\undefined\else\expandafter\endinput\fi
\let\mtx@posloaded\relax
\newwrite\mtx@pf
\immediate\openout\mtx@pf=\jobname.mtxpos
\newcount\mtx@page \mtx@page=0
\ifx\pdfsavepos\undefined
  \ifx\savepos\undefined
    \message{mtxpos: no savepos primitive}%
    \expandafter\endinput
  \else
    \let\mtx@savepos\savepos \let\mtx@lastx\lastxpos \let\mtx@lasty\lastypos
  \fi
\else
  \let\mtx@savepos\pdfsavepos \let\mtx@lastx\pdflastxpos \let\mtx@lasty\pdflastypos
\fi
% 쪽 번호: shipout 안에서 (write 가 풀리는 시점에) 증가시킨다
\let\mtx@shipout\shipout
\def\shipout{\global\advance\mtx@page\@ne \mtx@shipout}
\let\mtx@oldnwbar\n@wbar
\def\mtx@mark{%
  \mtx@savepos
  \edef\mtx@tmp{\write\mtx@pf{B,\the\barno,\noexpand\the\mtx@page,%
    \noexpand\the\mtx@lastx,\noexpand\the\mtx@lasty,%
    \the\systemheight,\the\lin@pos}}%
  \mtx@tmp}
\def\n@wbar{\mtx@mark\mtx@oldnwbar}
\catcode`\@=12
\endinput
"""

HOOK_LINE = r"%% \input mtxpos"

# 박자표를 그리지 않게 한다 (악보 조각용). 헤더의 `% MeterSig: Off` 가 켜져 있으면 컴파일할 때만
# 이 파일을 앱 임시 폴더에 풀고 `%% \input mtxnometer` 를 musixtex 가 로드된 뒤에 끼워 넣는다.
NOMETER_LINE = r"%% \input mtxnometer"
NOMETER_TEX = r"""\makeatletter
\def\generalmeter#1{\let\Writ@meters\relax \m@loop \s@l@ctm@t \m@t{{#1}{#1}{#1}{#1}}\repeat}
\makeatother
"""


@dataclass
class PosRec:
    index: int            # 등장 순서(0-기준)
    barno: int            # TeX 의 \barno
    page: int             # 1-기준
    x: float              # bp, 쪽 왼쪽 기준
    y: float              # bp, 쪽 아래 기준
    height: float         # bp, 시스템 높이(위쪽으로)
    left: float           # bp, 이 시스템의 왼쪽 가장자리(추정)


class PosMap:
    def __init__(self) -> None:
        self.recs: List[PosRec] = []
        self.by_pmx_bar: Dict[int, PosRec] = {}
        self.ok = False
        self.message = ""

    # ------------------------------------------------------------ 읽기
    @staticmethod
    def _dim(s: str) -> float:
        s = s.strip()
        if s.endswith("pt"):
            s = s[:-2]
        try:
            return float(s) / PT_PER_BP            # TeX pt -> bp
        except ValueError:
            return 0.0

    @classmethod
    def load(cls, path: str, pmx_bar_order: List[int]) -> "PosMap":
        pm = cls()
        try:
            with open(path, encoding="utf-8", errors="replace") as f:
                lines = [l.strip() for l in f if l.startswith("B,")]
        except OSError:
            pm.message = "위치 기록 파일 없음"
            return pm
        for i, ln in enumerate(lines):
            p = ln.split(",")
            if len(p) < 7:
                continue
            try:
                barno, page = int(p[1]), int(p[2])
                x, y = int(p[3]) / SP_PER_BP, int(p[4]) / SP_PER_BP
            except ValueError:
                continue
            h = cls._dim(p[5])
            lp = cls._dim(p[6])
            pm.recs.append(PosRec(i, barno, max(1, page), x, y, h, x - lp))
        # 박자 바뀜 직전 줄 끝처럼 같은 \barno 로 마디선이 한 번 더 기록되는 경우가 있다
        # (자장가: 4/4 → 3/4 로 바뀌는 마디 뒤 줄 끝에서 중복). 첫 기록(실제 마디선)만 남긴다.
        dedup: List[PosRec] = []
        for r in pm.recs:
            if dedup and dedup[-1].barno == r.barno:
                continue
            dedup.append(r)
        for i, r in enumerate(dedup):
            r.index = i
        pm.recs = dedup
        if not pm.recs:
            pm.message = "위치 기록이 비어 있음"
            return pm
        if len(pm.recs) != len(pmx_bar_order):
            pm.message = (f"위치 기록 {len(pm.recs)}개 ≠ pmx 마디 {len(pmx_bar_order)}개 "
                          "(다중 마디 쉼표/특수 구간?) - PDF 위치 기능 꺼짐")
            return pm
        for rec, bno in zip(pm.recs, pmx_bar_order):
            pm.by_pmx_bar[bno] = rec
        pm._fix_left_edges()
        pm.ok = True
        return pm

    def _same_system(self, a: PosRec, b: PosRec) -> bool:
        return a.page == b.page and abs(a.y - b.y) < 2.0

    def _fix_left_edges(self) -> None:
        """시스템 왼쪽 가장자리: \\lin@pos 로 추정한 값이 시스템마다 비슷하면 그걸 쓰고,
        엉뚱하면 같은 쪽의 다른 시스템들의 중앙값/최솟값으로 대체."""
        lefts = [r.left for r in self.recs]
        if lefts:
            med = sorted(lefts)[len(lefts) // 2]
            for r in self.recs:
                if not (0 <= r.left < r.x) or abs(r.left - med) > 40:
                    r.left = min(med, r.x - 20) if med < r.x else max(0.0, r.x - 120)

    # ------------------------------------------------------------ 질의
    def rect_for_bar(self, pmx_bar: int) -> Optional[Tuple[int, float, float, float, float]]:
        """-> (page, x0, y0_top, x1, y1_bottom) in bp, 쪽 *위* 기준이 아니라 PDF 좌표
        (아래 기준)로 (x0,ybot,x1,ytop) 를 돌려준다."""
        rec = self.by_pmx_bar.get(pmx_bar)
        if rec is None:
            return None
        prev = self.recs[rec.index - 1] if rec.index > 0 else None
        x0 = prev.x if (prev and self._same_system(prev, rec)) else rec.left
        ybot = rec.y - 4.0
        ytop = rec.y + rec.height + 4.0
        return rec.page, x0, ybot, rec.x, ytop

    def bar_at(self, page: int, x: float, y: float) -> Optional[int]:
        """쪽 좌표(bp, 아래 기준) -> pmx 마디 번호 (없으면 None)."""
        cand = [(r, abs((r.y + r.height / 2) - y)) for r in self.recs
                if r.page == page and r.y - 14 <= y <= r.y + r.height + 14]
        if not cand:
            return None
        # 가장 가까운 시스템 (y 기준) 선택
        best_y = min(cand, key=lambda t: t[1])[0].y
        row = [r for r, _ in cand if abs(r.y - best_y) < 2.0]
        row.sort(key=lambda r: r.x)
        pick = next((r for r in row if r.x >= x), row[-1])
        inv = {id(v): k for k, v in self.by_pmx_bar.items()}
        return inv.get(id(pick))
